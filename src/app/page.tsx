"use client";
import Link from "next/link";
import { useRouter } from "next/navigation";
import { useState } from "react";
import { ArrowRight, Loader2, Mic2, Sparkles, Users, FileText, ShieldCheck, Headphones } from "lucide-react";
import { api, BookCard, PreviewButton, usePoll, type LibraryBook } from "@/components/ui";

const STEPS = [
  { icon: FileText, title: "Upload a book", body: "PDF, EPUB, DOCX, DOC or TXT – or pick a public-domain classic." },
  { icon: Sparkles, title: "AI understands the story", body: "Finds where the story starts, detects chapters, scenes and who is speaking." },
  { icon: Users, title: "Characters get cast", body: "Each character receives a consistent voice matched to what the text actually says." },
  { icon: Headphones, title: "Listen", body: "A performed audiobook with narration, dialogue and synced text." },
];

export default function Landing() {
  const router = useRouter();
  const { data } = usePoll<{ books: LibraryBook[] }>("/api/books", 8000);
  const [busy, setBusy] = useState(false);
  const [err, setErr] = useState<string | null>(null);
  const recent = (data?.books ?? []).slice(0, 4);

  const startDemo = async () => {
    setBusy(true);
    setErr(null);
    try {
      const { book } = await api<{ book: { id: string } }>("/api/books/sample", { method: "POST", body: JSON.stringify({ mode: "multi" }) });
      router.push(`/books/${book.id}`);
    } catch (e) {
      setErr((e as Error).message);
      setBusy(false);
    }
  };

  return (
    <div className="space-y-16">
      <section className="grid items-center gap-10 pt-4 lg:grid-cols-[1.1fr_0.9fr] lg:pt-10">
        <div>
          <span className="chip mb-5"><Mic2 size={12} /> AI audiobook director · casting director · narrator</span>
          <h1 className="font-display text-5xl font-semibold leading-[1.02] tracking-tight sm:text-6xl lg:text-7xl">Give every character a voice.</h1>
          <p className="mt-6 max-w-xl text-lg text-ink-soft">Turn books into immersive audiobooks with AI-powered character casting, expressive narration, and voices that stay consistent from the first page to the last.</p>
          <div className="mt-8 flex flex-wrap gap-3">
            <Link href="/upload" className="btn-primary text-base">Upload a book <ArrowRight size={18} /></Link>
            <button type="button" onClick={startDemo} disabled={busy} className="btn-ghost text-base">{busy ? <Loader2 size={18} className="animate-spin" /> : <Sparkles size={18} />} Try the demo story</button>
            <Link href="/discover" className="btn-soft text-base">Browse free books</Link>
          </div>
          {err && <p className="mt-3 text-sm text-red-700">{err}</p>}
          <p className="mt-4 text-xs text-ink-mute">Runs on open-weight models on our own servers. No paid AI APIs. Your uploads stay private.</p>
        </div>
        <div className="card relative overflow-hidden p-6 sm:p-8">
          <div className="absolute -right-16 -top-16 h-48 w-48 rounded-full bg-accent-soft blur-2xl" aria-hidden />
          <p className="text-xs font-semibold uppercase tracking-wider text-ink-mute">Character casting preview</p>
          <ul className="mt-4 space-y-3">
            {[
              { name: "Narrator", desc: "Warm · clear · American", voice: "kokoro:af_heart", text: "The fog came in off the river a little after six, and by the time she reached the end of the quay she could no longer see the warehouses behind her." },
              { name: "Captain Bellamy", desc: "Older male · Scottish accent · deep, gravelly", voice: "kokoro:bm_george", text: "Don't be sorry. Be loud. The fog eats quiet things." },
              { name: "Mara", desc: "Young woman · soft, low voice", voice: "kokoro:af_nicole", text: "I didn't know I was expected." },
              { name: "Tom", desc: "Boy, ten years old", voice: "kokoro:am_puck", text: "Everyone's expected. That's how the quay works. You come, you wait, and the Captain decides." },
            ].map((c) => (
              <li key={c.name} className="flex items-center gap-3 rounded-2xl bg-paper-2 p-3">
                <PreviewButton voiceId={c.voice} text={c.text} size="sm" label={`Hear ${c.name}`} />
                <div className="min-w-0 flex-1">
                  <p className="text-sm font-semibold">{c.name}</p>
                  <p className="truncate text-xs text-ink-mute">{c.desc}</p>
                </div>
                <span className="hidden text-xs text-ink-mute sm:block">“{c.text.slice(0, 34)}…”</span>
              </li>
            ))}
          </ul>
          <p className="mt-4 text-[11px] text-ink-mute">Real samples generated by the same engine that performs your books.</p>
        </div>
      </section>

      {recent.length > 0 && (
        <section>
          <div className="mb-4 flex items-center justify-between">
            <h2 className="font-display text-2xl font-semibold">Continue listening</h2>
            <Link href="/library" className="btn-ghost">More +</Link>
          </div>
          <div className="grid grid-cols-2 gap-5 sm:grid-cols-3 lg:grid-cols-4">{recent.map((b) => <BookCard key={b.id} b={b} />)}</div>
        </section>
      )}

      <section>
        <h2 className="font-display text-3xl font-semibold">How it works</h2>
        <p className="mt-2 max-w-2xl text-ink-soft">Not text-to-speech. The book is understood first, then performed.</p>
        <ol className="mt-8 grid gap-4 sm:grid-cols-2 lg:grid-cols-4">
          {STEPS.map((s, i) => (
            <li key={s.title} className="card p-5">
              <div className="flex items-center gap-3"><span className="grid h-10 w-10 place-items-center rounded-2xl bg-accent-soft text-accent-deep"><s.icon size={18} /></span><span className="text-xs font-semibold text-ink-mute">Step {i + 1}</span></div>
              <h3 className="mt-4 font-semibold">{s.title}</h3>
              <p className="mt-1 text-sm text-ink-soft">{s.body}</p>
            </li>
          ))}
        </ol>
      </section>

      <section className="grid gap-4 lg:grid-cols-3">
        <div className="card p-6 lg:col-span-2">
          <h2 className="font-display text-2xl font-semibold">The pipeline behind every performance</h2>
          <div className="mt-4 flex flex-wrap gap-2 text-xs font-medium">
            {["Document understanding", "Story start detection", "Chapter detection", "Character registry", "Alias merging", "Narrator identification", "Dialogue attribution", "Thought detection", "Emotion & delivery", "Voice casting", "Voice locking", "Speech generation", "Audio assembly"].map((t, i, a) => (
              <span key={t} className="flex items-center gap-2"><span className="chip">{t}</span>{i < a.length - 1 && <ArrowRight size={12} className="text-ink-mute" />}</span>
            ))}
          </div>
          <p className="mt-5 text-sm text-ink-soft">Character attributes are only used when the text states them. Nothing is inferred from a name alone – unknown characters get neutral, high-quality voices.</p>
        </div>
        <div className="card p-6">
          <h3 className="flex items-center gap-2 font-semibold"><ShieldCheck size={18} className="text-success" /> Private by design</h3>
          <ul className="mt-3 space-y-2 text-sm text-ink-soft">
            <li>Uploads are stored privately and never shared or listed publicly.</li>
            <li>Analysis and speech run locally with open-weight models (Kokoro-82M, Apache-2.0).</li>
            <li>Free books come only from Project Gutenberg and are attributed to their source.</li>
            <li>Formats: PDF (incl. scanned via OCR), EPUB, DOCX, DOC, TXT.</li>
          </ul>
        </div>
      </section>

      <footer className="border-t border-line pt-8 pb-4 text-xs text-ink-mute">
        <p>VoxLibris · Open-weight AI audiobook studio. Text-to-speech by Kokoro-82M (Apache-2.0). Public-domain catalog via Project Gutenberg / Gutendex. See MODEL_LICENSES.md for attribution.</p>
      </footer>
    </div>
  );
}
